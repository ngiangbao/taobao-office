const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  getCfg: () => ipcRenderer.invoke('cfg:get'),
  setCfg: (c) => ipcRenderer.invoke('cfg:set', c),
  importGroups: (url) => ipcRenderer.invoke('groups:import', url),
  syncStatus: () => ipcRenderer.invoke('sync:status'),
  connectSync: (d) => ipcRenderer.invoke('sync:connect', d),
  syncNow: () => ipcRenderer.invoke('sync:now'),
  disconnectSync: () => ipcRenderer.invoke('sync:disconnect'),
  onSync: (cb) => ipcRenderer.on('sync:update', (_, result) => cb(result)),
  listAgents: () => ipcRenderer.invoke('agents:list'),
  addAgent: (d) => ipcRenderer.invoke('agents:add', d),
  removeAgent: (id) => ipcRenderer.invoke('agents:remove', id),
  resetAgent: (id) => ipcRenderer.invoke('agents:reset', id),
  stopAll: () => ipcRenderer.invoke('agents:stop'),
  onAgents: (cb) => ipcRenderer.on('agents:update', (_, a) => cb(a)),
  openLogin: () => ipcRenderer.invoke('login:open'),
  version: () => ipcRenderer.invoke('app:version'),
  checkUpdates: () => ipcRenderer.invoke('app:updates:check'),
  onUpdate: (cb) => ipcRenderer.on('update:status', (_, u) => cb(u)),
  officeUrl: () => ipcRenderer.invoke('office:url'),
  onOfficeError: (cb) => ipcRenderer.on('office:error', (_, m) => cb(m)),
  onOfficeReady: (cb) => ipcRenderer.on('office:ready', (_, u) => cb(u)),
  onOfficeError: (cb) => ipcRenderer.on('office:error', (_, t) => cb(t)),
  historyQuery: (o) => ipcRenderer.invoke('history:query', o),
  historyDelete: (o) => ipcRenderer.invoke('history:delete', o),
  openHistoryDir: () => ipcRenderer.invoke('history:open'),
  listCustomers: () => ipcRenderer.invoke('customers:list'),
  exportCustomers: () => ipcRenderer.invoke('customers:export'),
  renameCustomer: (d) => ipcRenderer.invoke('customers:rename', d),
  pauseCustomer: (d) => ipcRenderer.invoke('customers:pause', d),
  refreshCustomer: (code) => ipcRenderer.invoke('customers:refresh', code),
  customerProfile: (code) => ipcRenderer.invoke('customers:profile', code),
  onCustomers: (cb) => ipcRenderer.on('customers:update', (_, l) => cb(l)),
  listRevenue: () => ipcRenderer.invoke('revenue:list'),
  addRevenue: (d) => ipcRenderer.invoke('revenue:add', d),
  voidRevenue: (id) => ipcRenderer.invoke('revenue:void', id),
  inboxManual: (d) => ipcRenderer.invoke('inbox:manual', d),
  inboxPoll: () => ipcRenderer.invoke('inbox:poll'),
  onInbox: (cb) => ipcRenderer.on('inbox:result', (_, r) => cb(r)),
  listApprovals: () => ipcRenderer.invoke('approvals:list'),
  editApproval: (d) => ipcRenderer.invoke('approvals:edit', d),
  decideApproval: (d) => ipcRenderer.invoke('approvals:decide', d),
  onApprovals: (cb) => ipcRenderer.on('approvals:update', (_, l) => cb(l)),
  openData: () => ipcRenderer.invoke('log:open'),
});
